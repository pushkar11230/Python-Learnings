a = 60 # Assignment Operator
b = 30


# Arithematic Operators
print(a + b)
print(a - b)
print(a * b)
print(a / b) # Returns Float
print(a // b) # Returns Integer
print(a ** b) 
print(a % b)


# Comparision Operators
print(a == b)
print(a != b)
print(a > b)
print(a < b)
print(a >= b)
print(a <= b)


# Assignment Operators
a += 10
print(a)

b -= 5
print(b)



# Logical Operators
print(False and True)
print(True and True)
print(False or True)
print(True or True)
print(False or False)
print(not(True))
